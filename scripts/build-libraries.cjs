const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const names=['abb','phoenix-contact','finder'];
const seen=new Set();
const libraries=names.map(name=>{
  const data=JSON.parse(fs.readFileSync(path.join(root,'libraries',name+'.json'),'utf8'));
  if(data.schemaVersion!==1||data.id!==name||!data.manufacturer||typeof data.coverage?.complete!=='boolean')throw new Error('Invalid catalogue '+name);
  for(const family of data.families)for(const p of family.products){
    const key=name+':'+p.id;
    if(seen.has(key)||!p.id||!p.model||!p.symbol||!p.verification)throw new Error('Invalid/duplicate product '+key);
    seen.add(key);
  }
  return data;
});
const output='// Generated by scripts/build-libraries.cjs. Edit manufacturer JSON files instead.\nwindow.CABEL_CATALOGS='+JSON.stringify(libraries)+';\n';
const target=path.join(root,'libraries','catalog.js');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw new Error('Catalogue bundle is stale; run node scripts/build-libraries.cjs');}
else fs.writeFileSync(target,output);
console.log(`${libraries.length} manufacturer libraries, ${seen.size} entries; ${process.argv.includes('--check')?'bundle verified':'bundle generated'}`);
